        /// <summary>Writes every demo-tools write operation to demo_tools_log.txt so demo edits stay traceable.</summary>
        private void Audit(string action, string details)
        {
            var user = HttpContext.Session.GetString("UserEmail")
                       ?? HttpContext.Session.GetString("UserRole")
                       ?? "unknown";
            _auditLogger.Log(Microsoft.Extensions.Logging.LogLevel.Information, 0,
                $"[{action}] by={user} {details}", null, (state, _) => state);
        }

        private bool IsAdminOrStaff()
        {
            var role = HttpContext.Session.GetString("UserRole");
            return string.Equals(role, "admin", StringComparison.OrdinalIgnoreCase) ||
                   string.Equals(role, "staff", StringComparison.OrdinalIgnoreCase);
        }

        [HttpGet]
        [Route("api/admin/demo-tools/tables")]
        public IActionResult GetTables()
        {
            if (!IsAdminOrStaff()) return Unauthorized(new { success = false, message = "Bạn không có quyền thực hiện hành động này!" });

            try
            {
                var tables = _context.Model.GetEntityTypes()
                    .Where(et => et.GetTableName() != null)
                    .Select(et => new
                    {
                        name = et.GetTableName(),
                        columns = GetColumnInfo(et).Select(c => new
                        {
                            name = c.Name,
                            storeType = c.StoreType,
                            clrType = c.ClrType.Name,
                            isPrimaryKey = c.IsPrimaryKey,
                            isNullable = c.IsNullable,
                            isAutoGenerated = c.IsAutoGenerated,
                            enumLabels = c.EnumLabels
                        })
                    })
                    .OrderBy(t => t.name)
                    .ToList();

                return Ok(new { success = true, tables });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }

        [HttpGet]
        [Route("api/admin/demo-tools/tables/{table}/rows")]
        public async Task<IActionResult> GetRows(string table, int page = 1, int pageSize = 20, string? search = null, string? sortBy = null, string? sortDir = null)
        {
            if (!IsAdminOrStaff()) return Unauthorized(new { success = false, message = "Bạn không có quyền thực hiện hành động này!" });

            var entityType = FindEntityType(table);
            if (entityType == null) return NotFound(new { success = false, message = $"Không tìm thấy bảng '{table}'." });

            if (page < 1) page = 1;
            if (pageSize < 1 || pageSize > 200) pageSize = 20;

            try
            {
                var tableName = entityType.GetTableName()!;
                var columns = GetColumnInfo(entityType);
                var pkColumns = columns.Where(c => c.IsPrimaryKey).Select(c => c.Name).ToList();
                // Sort column must exist in the EF model — rejects arbitrary identifiers
                var orderBy = pkColumns.Count > 0
                    ? string.Join(", ", pkColumns.Select(Quote))
                    : Quote(columns[0].Name);
                if (!string.IsNullOrWhiteSpace(sortBy))
                {
                    var sortColumn = columns.FirstOrDefault(c => string.Equals(c.Name, sortBy, StringComparison.OrdinalIgnoreCase));
                    if (sortColumn == null)
                    {
                        return BadRequest(new { success = false, message = $"Cột sort '{sortBy}' không tồn tại trong bảng '{table}'." });
                    }
                    var direction = string.Equals(sortDir, "desc", StringComparison.OrdinalIgnoreCase) ? "DESC" : "ASC";
                    orderBy = $"{Quote(sortColumn.Name)} {direction}";
                }

                // Search: match the term against every column, cast to text so it works for numbers/dates too
                var whereClause = "";
                if (!string.IsNullOrWhiteSpace(search))
                {
                    var likeConditions = columns.Select(c => $"{Quote(c.Name)}::text ILIKE @search");
                    whereClause = $" WHERE ({string.Join(" OR ", likeConditions)})";
                }

                var result = await WithConnectionAsync(async conn =>
                {
                    long totalCount;
                    using (var countCmd = conn.CreateCommand())
                    {
                        countCmd.CommandText = $"SELECT COUNT(*) FROM {Quote(tableName)}{whereClause}";
                        AddSearchParameter(countCmd, whereClause, search);
                        totalCount = Convert.ToInt64(await countCmd.ExecuteScalarAsync());
                    }

                    var rows = new List<Dictionary<string, object?>>();
                    using (var cmd = conn.CreateCommand())
                    {
                        cmd.CommandText =
                            $"SELECT * FROM {Quote(tableName)}{whereClause} ORDER BY {orderBy} " +
                            $"LIMIT {pageSize} OFFSET {(page - 1) * pageSize}";
                        AddSearchParameter(cmd, whereClause, search);
                        using var reader = await cmd.ExecuteReaderAsync();
                        while (await reader.ReadAsync())
                        {
                            var row = new Dictionary<string, object?>();
                            for (int i = 0; i < reader.FieldCount; i++)
                            {
                                row[reader.GetName(i)] = ReadValue(reader.GetValue(i));
                            }
                            rows.Add(row);
                        }
                    }

                    return new { totalCount, rows };
                });

                return Ok(new { success = true, page, pageSize, totalCount = result.totalCount, rows = result.rows });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }

        public class RowRequest
        {
            public Dictionary<string, JsonElement>? Pk { get; set; }
            public Dictionary<string, JsonElement>? Values { get; set; }
        }

        [HttpPut]
        [Route("api/admin/demo-tools/tables/{table}/rows")]
        public async Task<IActionResult> UpdateRow(string table, [FromBody] RowRequest request)
        {
            if (!IsAdminOrStaff()) return Unauthorized(new { success = false, message = "Bạn không có quyền thực hiện hành động này!" });

            var entityType = FindEntityType(table);
            if (entityType == null) return NotFound(new { success = false, message = $"Không tìm thấy bảng '{table}'." });
            if (request?.Pk == null || request.Pk.Count == 0) return BadRequest(new { success = false, message = "Thiếu khóa chính (pk)." });
            if (request.Values == null || request.Values.Count == 0) return BadRequest(new { success = false, message = "Không có cột nào để cập nhật." });

            var columns = GetColumnInfo(entityType);

            try
            {
                var affected = await WithConnectionAsync(async conn =>
                {
                    using var cmd = conn.CreateCommand();
                    var setParts = new List<string>();
                    int i = 0;
                    foreach (var (colName, jsonValue) in request.Values)
                    {
                        var col = FindColumnOrThrow(columns, colName, table);
                        setParts.Add($"{Quote(col.Name)} = {AddTypedParameter(cmd, $"v{i++}", jsonValue, col)}");
                    }

                    var whereClause = BuildPkWhere(cmd, columns, request.Pk, table);
                    cmd.CommandText = $"UPDATE {Quote(entityType.GetTableName()!)} SET {string.Join(", ", setParts)} WHERE {whereClause}";
                    return await cmd.ExecuteNonQueryAsync();
                });

                if (affected == 0) return NotFound(new { success = false, message = "Không tìm thấy row với khóa chính này." });
                Audit($"UPDATE {table}", $"pk={JsonSerializer.Serialize(request.Pk)} values={JsonSerializer.Serialize(request.Values)}");
                return Ok(new { success = true, message = $"Đã cập nhật {affected} row.", affected });
            }
            catch (ArgumentException ex)
            {
                return BadRequest(new { success = false, message = ex.Message });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }

        [HttpPost]
        [Route("api/admin/demo-tools/tables/{table}/rows")]
        public async Task<IActionResult> InsertRow(string table, [FromBody] RowRequest request)
        {
            if (!IsAdminOrStaff()) return Unauthorized(new { success = false, message = "Bạn không có quyền thực hiện hành động này!" });

            var entityType = FindEntityType(table);
            if (entityType == null) return NotFound(new { success = false, message = $"Không tìm thấy bảng '{table}'." });
            if (request?.Values == null || request.Values.Count == 0) return BadRequest(new { success = false, message = "Không có dữ liệu để thêm." });

            var columns = GetColumnInfo(entityType);

            try
            {
                var createdRow = await WithConnectionAsync(async conn =>
                {
                    using var cmd = conn.CreateCommand();
                    var colNames = new List<string>();
                    var placeholders = new List<string>();
                    int i = 0;
                    foreach (var (colName, jsonValue) in request.Values)
                    {
                        var col = FindColumnOrThrow(columns, colName, table);
                        if (col.IsAutoGenerated) continue; // identity PK — let the DB generate it
                        colNames.Add(Quote(col.Name));
                        placeholders.Add(AddTypedParameter(cmd, $"v{i++}", jsonValue, col));
                    }
                    if (colNames.Count == 0) throw new ArgumentException("Không có cột hợp lệ nào để thêm.");

                    cmd.CommandText =
                        $"INSERT INTO {Quote(entityType.GetTableName()!)} ({string.Join(", ", colNames)}) " +
                        $"VALUES ({string.Join(", ", placeholders)}) RETURNING *";

                    using var reader = await cmd.ExecuteReaderAsync();
                    if (!await reader.ReadAsync()) return null;
                    var row = new Dictionary<string, object?>();
                    for (int f = 0; f < reader.FieldCount; f++)
                    {
                        row[reader.GetName(f)] = ReadValue(reader.GetValue(f));
                    }
                    return row;
                });

                Audit($"INSERT {table}", $"values={JsonSerializer.Serialize(request.Values)}");
                return Ok(new { success = true, message = "Đã thêm row mới.", row = createdRow });
            }
            catch (ArgumentException ex)
            {
                return BadRequest(new { success = false, message = ex.Message });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }

