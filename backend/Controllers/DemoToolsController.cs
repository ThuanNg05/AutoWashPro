        /// <summary>
        /// Shifts every timestamp of a booking (and its queue rows) by N minutes so demo
        /// scenarios can be triggered instantly: shift ScheduledAt into the past to fire
        /// no-show, into the near future to fire reminders, or move Queue.CheckInAt back
        /// to jump wash stages. Shifting into the future re-arms the email flags.
        /// </summary>
        [HttpPost]
        [Route("api/admin/demo-tools/bookings/{id}/shift-time")]
        public async Task<IActionResult> ShiftBookingTime(int id, int minutes)
        {
            if (!IsAdminOrStaff()) return Unauthorized(new { success = false, message = "Bạn không có quyền thực hiện hành động này!" });
            if (minutes == 0) return BadRequest(new { success = false, message = "Số phút phải khác 0." });

            try
            {
                var booking = await _context.Bookings.FirstOrDefaultAsync(b => b.BookingId == id);
                if (booking == null) return NotFound(new { success = false, message = $"Không tìm thấy booking #{id}." });

                var shift = TimeSpan.FromMinutes(minutes);
                booking.ScheduledAt += shift;
                booking.CreatedAt += shift;
                if (booking.CheckInAt.HasValue) booking.CheckInAt += shift;
                if (booking.ConfirmedAt.HasValue) booking.ConfirmedAt += shift;
                if (booking.WashingAt.HasValue) booking.WashingAt += shift;
                if (booking.CompletedAt.HasValue) booking.CompletedAt += shift;
                if (booking.NoShowAt.HasValue) booking.NoShowAt += shift;
                if (booking.CancelledAt.HasValue) booking.CancelledAt += shift;
                if (booking.CheckedOutAt.HasValue) booking.CheckedOutAt += shift;

                bool flagsReset = false;
                if (booking.ScheduledAt > DateTime.Now)
                {
                    booking.Reminder1Sent = false;
                    booking.Reminder2Sent = false;
                    booking.NoShowEmailSent = false;
                    flagsReset = true;
                }

                var queues = await _context.Queues.Where(q => q.BookingId == id).ToListAsync();
                foreach (var q in queues)
                {
                    q.CheckInAt += shift;
                    if (q.StartedAt.HasValue) q.StartedAt += shift;
                    if (q.CompletedAt.HasValue) q.CompletedAt += shift;
                }

                // Update BookingTask rows for single source of truth workflow
                var tasks = await _context.BookingTasks
                    .Where(t => t.BookingId == id)
                    .OrderBy(t => t.SequenceOrder)
                    .ToListAsync();

                foreach (var task in tasks)
                {
                    if (task.StartedAt.HasValue) task.StartedAt += shift;
                    if (task.CompletedAt.HasValue) task.CompletedAt += shift;
                }

                if (minutes < 0)
                {
                    var activeTimedTask = tasks.FirstOrDefault(t => t.Status == BookingTaskStatus.InProgress && (t.TaskType == "CheckIn" || t.TaskType == "Washing" || t.TaskType == "AddonProcessing"));
                    if (activeTimedTask != null)
                    {
                        activeTimedTask.Status = BookingTaskStatus.Completed;
                        activeTimedTask.CompletedAt = DateTime.Now;

                        var nextPendingTask = tasks.FirstOrDefault(t => t.Status == BookingTaskStatus.Pending);
                        if (nextPendingTask != null)
                        {
                            nextPendingTask.Status = BookingTaskStatus.InProgress;
                            nextPendingTask.StartedAt = DateTime.Now;
                            foreach (var q in queues)
                            {
                                q.CurrentStage = nextPendingTask.TaskType;
                            }
                        }
                    }
                }

                await _context.SaveChangesAsync();

                Audit("SHIFT bookings", $"bookingId={id} minutes={minutes} queues={queues.Count} flagsReset={flagsReset}");
                return Ok(new
                {
                    success = true,
                    message = $"Đã dịch thời gian booking #{id} {(minutes > 0 ? "+" : "")}{minutes} phút" +
                              (flagsReset ? " (đã reset các cờ email nhắc lịch)." : "."),
                    scheduledAt = booking.ScheduledAt.ToString("yyyy-MM-ddTHH:mm:ss"),
                    queuesShifted = queues.Count,
                    flagsReset
                });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }

        /// <summary>
        /// Demo-only check-in: performs the same Queue-creation logic as the real
        /// check-in (AdminBookingService.CheckInBookingAsync) but skips the ±15min
        /// window and same-day checks — and never touches any *At column on the
        /// booking, so the customer's actual appointment schedule stays untouched.
        /// </summary>
        [HttpPost]
        [Route("api/admin/demo-tools/bookings/{id}/force-checkin")]
        public async Task<IActionResult> ForceCheckIn(int id)
        {
            if (!IsAdminOrStaff()) return Unauthorized(new { success = false, message = "Bạn không có quyền thực hiện hành động này!" });

            try
            {
                var booking = await _context.Bookings
                    .Include(b => b.Customer).ThenInclude(c => c.Account)
                    .Include(b => b.Customer).ThenInclude(c => c.Tier)
                    .Include(b => b.Vehicle)
                    .FirstOrDefaultAsync(b => b.BookingId == id);
                if (booking == null) return NotFound(new { success = false, message = $"Không tìm thấy đơn đặt lịch #{id}." });

                if (booking.Status == BookingStatus.NoShow || booking.Status == BookingStatus.Cancelled || booking.Status == BookingStatus.Completed)
                    return BadRequest(new { success = false, message = $"Không thể check-in lịch đặt đã {(booking.Status == BookingStatus.NoShow ? "quá hạn (No-Show)" : booking.Status == BookingStatus.Cancelled ? "bị hủy" : "hoàn thành")}." });

                if (booking.Status != BookingStatus.Confirmed)
                    return BadRequest(new { success = false, message = "Chỉ đơn đặt lịch đang ở trạng thái 'Đã xác nhận' mới có thể thực hiện check-in." });

                var strategy = _context.Database.CreateExecutionStrategy();
                return await strategy.ExecuteAsync(async () =>
                {
                    using var transaction = await _context.Database.BeginTransactionAsync();
                    try
                    {
                        await _context.Database.ExecuteSqlRawAsync("SELECT pg_advisory_xact_lock(2410);");

                        var existingQueue = await _context.Queues
                            .FirstOrDefaultAsync(q => q.BookingId == booking.BookingId && q.Status != QueueStatus.Cancelled);

                        int queueId;
                        string message;
                        if (existingQueue != null)
                        {
                            booking.Status = BookingStatus.CheckedIn;
                            await _context.SaveChangesAsync();
                            await transaction.CommitAsync();
                            queueId = existingQueue.QueueId;
                            message = "Đơn đặt lịch đã được check-in vào hàng đợi.";
                        }
                        else
                        {
                            var today = DateTime.Today;
                            var lastPos = await _context.Queues
                                .Where(q => q.CheckInAt.Date == today && q.Status != QueueStatus.Cancelled)
                                .Select(q => (int?)q.Position)
                                .MaxAsync() ?? 0;

                            var newQueue = new Queue
                            {
                                BookingId = booking.BookingId,
                                VehicleId = booking.VehicleId,
                                CustomerId = booking.CustomerId,
                                LicensePlate = booking.Vehicle?.LicensePlate?.ToUpper()?.Trim() ?? string.Empty,
                                CustomerName = booking.Customer?.Account?.FullName ?? "Khách vãng lai",
                                TierId = booking.Customer?.TierId ?? 1,
                                Status = QueueStatus.Waiting,
                                Position = lastPos + 1,
                                CheckInAt = DateTime.Now,
                                StaffNote = booking.Notes ?? string.Empty
                            };
                            booking.Status = BookingStatus.CheckedIn;
                            _context.Queues.Add(newQueue);
                            await _context.SaveChangesAsync();
                            await transaction.CommitAsync();
                            queueId = newQueue.QueueId;
                            message = "Check-in thành công! Xe đã được thêm vào hàng đợi.";
                        }

                        Audit("FORCE-CHECKIN bookings", $"bookingId={id} queueId={queueId} bypassedWindow=true");
                        return Ok(new { success = true, message, queueId });
                    }
                    catch (Exception)
                    {
                        await transaction.RollbackAsync();
                        throw;
                    }
                });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }

        private static ColumnInfo FindColumnOrThrow(List<ColumnInfo> columns, string name, string table)
        {
            return columns.FirstOrDefault(c => string.Equals(c.Name, name, StringComparison.OrdinalIgnoreCase))
                ?? throw new ArgumentException($"Cột '{name}' không tồn tại trong bảng '{table}'.");
        }

        /// <summary>
        /// Adds a parameter carrying the JSON value as text and returns the SQL placeholder
        /// with a cast to the column's store type — values never get concatenated into SQL.
        /// </summary>
        private static string AddTypedParameter(DbCommand cmd, string name, JsonElement jsonValue, ColumnInfo col)
        {
            var p = cmd.CreateParameter();
            p.ParameterName = name;
            if (jsonValue.ValueKind == JsonValueKind.Null ||
                (jsonValue.ValueKind == JsonValueKind.String && jsonValue.GetString() == "" && col.IsNullable && col.ClrType != typeof(string)))
            {
                p.Value = DBNull.Value;
                cmd.Parameters.Add(p);
                return $"@{name}";
            }
            p.Value = jsonValue.ValueKind == JsonValueKind.String ? jsonValue.GetString()! : jsonValue.GetRawText();
            cmd.Parameters.Add(p);
            return $"@{name}::{col.StoreType}";
        }

        private static string BuildPkWhere(DbCommand cmd, List<ColumnInfo> columns, Dictionary<string, JsonElement> pk, string table)
        {
            var pkColumns = columns.Where(c => c.IsPrimaryKey).ToList();
            if (pkColumns.Count == 0) throw new ArgumentException($"Bảng '{table}' không có khóa chính — không hỗ trợ sửa/xóa.");

            var parts = new List<string>();
            int i = 0;
            foreach (var pkCol in pkColumns)
            {
                if (!pk.TryGetValue(pkCol.Name, out var value) &&
                    !pk.TryGetValue(pkCol.Name.ToLowerInvariant(), out value))
                {
                    throw new ArgumentException($"Thiếu giá trị khóa chính '{pkCol.Name}'.");
                }
                parts.Add($"{Quote(pkCol.Name)} = {AddTypedParameter(cmd, $"k{i++}", value, pkCol)}");
            }
            return string.Join(" AND ", parts);
        }

        private sealed class ColumnInfo
        {
            public string Name { get; init; } = string.Empty;
            public string StoreType { get; init; } = string.Empty;
            public Type ClrType { get; init; } = typeof(object);
            public bool IsPrimaryKey { get; init; }
            public bool IsNullable { get; init; }
            public bool IsAutoGenerated { get; init; }
            public Dictionary<int, string>? EnumLabels { get; init; }
        }

        private IEntityType? FindEntityType(string tableName)
        {
            return _context.Model.GetEntityTypes()
                .FirstOrDefault(et => string.Equals(et.GetTableName(), tableName, StringComparison.OrdinalIgnoreCase));
        }

        /// <summary>Quotes a Postgres identifier; the only untrusted part of built SQL — values always go through parameters.</summary>
        private static string Quote(string identifier) => "\"" + identifier.Replace("\"", "\"\"") + "\"";

        private async Task<T> WithConnectionAsync<T>(Func<DbConnection, Task<T>> action)
        {
            var conn = _context.Database.GetDbConnection();
            bool wasOpen = conn.State == System.Data.ConnectionState.Open;
            if (!wasOpen) await conn.OpenAsync();
            try
            {
                return await action(conn);
            }
            finally
            {
                if (!wasOpen) await conn.CloseAsync();
            }
        }

        [HttpGet]
        [Route("api/admin/demo-tools/audit-db")]
        public async Task<IActionResult> AuditDatabase()
        {
            try
            {
                var services = await _context.Services.AsNoTracking().OrderBy(s => s.ServiceId).ToListAsync();
                var tiers = await _context.Tiers.AsNoTracking().OrderBy(t => t.TierId).ToListAsync();
                var loyaltyConfig = await _context.LoyaltyConfigs.AsNoTracking().FirstOrDefaultAsync();
                var rewards = await _context.Rewards.AsNoTracking().OrderBy(r => r.RewardId).ToListAsync();
